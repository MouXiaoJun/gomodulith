func TestExportContract(t *testing.T) {
	files := defaultFixture()
	files["internal/user/events/events.go"] = eventFile("events", []string{"UserRegistered"}, nil)
	files["internal/notifications/api/api.go"] = goFile("api", []string{fixtureModule + "/internal/user/events"})
	files["internal/notifications/domain/dom.go"] = goFile("domain", nil)
	writeFixture(t, files)

	app := New().
		Module("user", "./internal/user/...").
		Module("order", "./internal/order/...").
		Module("payment", "./internal/payment/...").
		Module("notifications", "./internal/notifications/...")
	app.ModuleRules("user").PublishEvents("UserRegistered")
	app.ModuleRules("order").AllowDependencies("user")
	app.ModuleRules("notifications").AllowDependencies("user").EventDrivenFrom("user")
	if err := LoadExplicit(ctx, app, "./..."); err != nil {
		t.Fatalf("LoadExplicit: %v", err)
	}

	doc, err := app.ExportContract()
	if err != nil {
		t.Fatalf("ExportContract: %v", err)
	}
	s := string(doc)

	for _, want := range []string{
		"# " + ContractHeader,
		"Generated by gomodulith v" + Version,
		"### user",
		"### order",
		"### notifications",
		"Publishes events: UserRegistered",
		"Allowed dependencies: user",
		"Event-driven towards: user",
		"## Rules",
		"## Verification status",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("contract missing %q:\n%s", want, s)
		}
	}
}

