func TestScanDir(t *testing.T) {
	fixtureDir := writeFixture(t, defaultFixture())
	chdir(t, t.TempDir())

	app := ScanDir(t, fixtureDir, "./...")
	res, err := app.Verify()
	if err != nil {
		t.Fatalf("Verify: %v", err)
	}
	if !res.HasCode(CodeCrossModulePrivate) {
		t.Fatalf("expected cross-module violation from scanned dir:\n%s", Report(res))
	}
	if app.WorkingDir() != fixtureDir {
		t.Fatalf("WorkingDir = %q, want %q", app.WorkingDir(), fixtureDir)
	}
}

