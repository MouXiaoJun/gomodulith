func TestConfigFileEventFields(t *testing.T) {
	data := []byte(`
modules:
  user:
    patterns: ["./internal/user/..."]
    publish_events: ["UserRegistered"]
  notifications:
    patterns: ["./internal/notifications/..."]
    event_driven_from: ["user"]
`)
	fc, err := ParseConfig(data, ConfigYAML)
	if err != nil {
		t.Fatalf("ParseConfig: %v", err)
	}
	user := fc.Modules["user"]
	if len(user.PublishEvents) != 1 || user.PublishEvents[0] != "UserRegistered" {
		t.Errorf("user publish_events = %v", user.PublishEvents)
	}
	notif := fc.Modules["notifications"]
	if len(notif.EventDrivenFrom) != 1 || notif.EventDrivenFrom[0] != "user" {
		t.Errorf("notifications event_driven_from = %v", notif.EventDrivenFrom)
	}
}

func TestConfigFileEventElement(t *testing.T) {
	fc, err := ParseConfig([]byte("event_element: evt\n"), ConfigYAML)
	if err != nil {
		t.Fatalf("ParseConfig: %v", err)
	}
	if fc.EventElement != "evt" {
		t.Errorf("EventElement = %q", fc.EventElement)
	}
	if got := fc.config().EventElement; got != "evt" {
		t.Errorf("config EventElement = %q", got)
	}
}
